#!/usr/bin/env python3
"""Generate governance/DOCUMENT_REGISTRY.md for Markdown files in the Git index.

Usage:
    python tools/build_document_registry.py          # write the registry
    python tools/build_document_registry.py --check  # exit 1 if the registry is stale

Standard library only. The output is deterministic (sorted paths, no timestamps).
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "governance" / "DOCUMENT_REGISTRY.md"
SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "__pycache__", ".pytest_cache"}

KINDS = (
    ("team/agents/", "Agent"),
    ("team/skills/", "Skill"),
    ("docs/changes/", "Change record"),
    ("docs/templates/", "Template"),
    ("governance/", "Governance"),
    ("core/", "Project state"),
    ("docs/", "Documentation"),
    ("reports/", "Report"),
)


def kind_of(rel: str) -> str:
    for prefix, kind in KINDS:
        if rel.startswith(prefix):
            return kind
    return "Root document"


def title_of(path: Path) -> str:
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if stripped.startswith("#"):
                return stripped.lstrip("#").strip().replace("|", "/")
            if stripped.startswith("name:"):
                return stripped[len("name:"):].strip().replace("|", "/")
    except (OSError, UnicodeDecodeError):
        return "(unreadable)"
    return "(no heading)"


def collect() -> list[tuple[str, str, str]]:
    result = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "--cached", "-z"],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    tracked = [ROOT / value for value in result.stdout.decode("utf-8").split("\0") if value.endswith(".md")]
    rows = []
    for path in sorted(tracked):
        rel = path.relative_to(ROOT).as_posix()
        if any(part in SKIP_DIRS for part in path.relative_to(ROOT).parts) or not path.is_file():
            continue
        if rel == "governance/DOCUMENT_REGISTRY.md":
            continue
        rows.append((rel, kind_of(rel), title_of(path)))
    return rows


def render(rows: list[tuple[str, str, str]]) -> str:
    kinds: dict[str, int] = {}
    for _, kind, _ in rows:
        kinds[kind] = kinds.get(kind, 0) + 1
    lines = [
        "# Document registry",
        "",
        "**Generated by `tools/build_document_registry.py` - do not edit by hand.** One row per Markdown",
        "document in the Git index (tracked or staged for commit). `--check` exits 1 when this file is stale.",
        "",
        f"Markdown documents: **{len(rows)}**",
        "",
        "| kind | documents |",
        "|---|---|",
    ]
    for kind in sorted(kinds):
        lines.append(f"| {kind} | {kinds[kind]} |")
    lines += ["", "| path | kind | title |", "|---|---|---|"]
    for rel, kind, title in rows:
        lines.append(f"| `{rel}` | {kind} | {title} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(collect())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("DOCUMENT_REGISTRY.md is stale; run tools/build_document_registry.py")
            return 1
        print("DOCUMENT_REGISTRY.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
