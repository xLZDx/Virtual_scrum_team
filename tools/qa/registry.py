"""Load the committed QA registry and validate its v2 manifest projection."""

from __future__ import annotations

import ast
import hashlib
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any

from tools.vst.contracts import ContractError, manifest_sha256, validate_task_manifest


PRIMARY_CATEGORIES = ("functional", "integration", "api", "e2e", "seeded-failure")
REGRESSION_CATEGORIES = ("functional", "integration", "api", "e2e")
MAX_REGISTRY_BYTES = 512 * 1024
MAX_TEST_SOURCE_BYTES = 1024 * 1024
MAX_REGISTRY_TEST_IDS = 2048
MAX_REGISTRY_SOURCE_BYTES = 4 * 1024 * 1024
GIT_COMMAND_TIMEOUT_SECONDS = 5
GIT_TIMEOUT_RETRIES = 1
SEEDED_CATALOG_PATH = "docs/qa/seeded_failures.json"
MAX_SEEDED_CATALOG_BYTES = 128 * 1024
_FIXTURE_ID = re.compile(r"[a-z0-9][a-z0-9._-]{0,63}")
_REJECTION_CODE = re.compile(r"[A-Z][A-Z0-9_]{0,63}")


def _reject_duplicate_json_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON object key: {key}")
        result[key] = value
    return result


def _read_repo_json(root: Path, relative_path: str, *, max_bytes: int) -> tuple[dict, bytes]:
    if os.path.isabs(relative_path) or ".." in Path(relative_path).parts:
        raise ContractError("registry and manifest paths must be repository-relative")
    target = root / relative_path
    if target.is_symlink() or not target.is_file():
        raise ContractError(f"repository JSON file is missing or linked: {relative_path}")
    resolved = target.resolve(strict=True)
    if root.resolve() not in resolved.parents:
        raise ContractError("repository JSON file escapes the worktree")
    with resolved.open("rb") as handle:
        raw = handle.read(max_bytes + 1)
    if len(raw) > max_bytes:
        raise ContractError(f"repository JSON file exceeds {max_bytes} bytes")
    try:
        parsed = json.loads(raw.decode("utf-8"), object_pairs_hook=_reject_duplicate_json_keys)
    except (UnicodeDecodeError, ValueError) as exc:
        raise ContractError(f"repository JSON file is malformed: {relative_path}") from exc
    if not isinstance(parsed, dict):
        raise ContractError(f"repository JSON root must be an object: {relative_path}")
    return parsed, raw


def _git_file_is_tracked(root: Path, relative_path: str) -> bool:
    try:
        result = _run_git_with_timeout_retry(
            ["git", "ls-files", "--error-unmatch", "--", relative_path],
            cwd=root,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def _run_git_with_timeout_retry(command: list[str], **kwargs: Any) -> subprocess.CompletedProcess:
    """Retry one transient timeout; keep the command bounded and fail closed."""
    for attempt in range(GIT_TIMEOUT_RETRIES + 1):
        try:
            return subprocess.run(
                command,
                timeout=GIT_COMMAND_TIMEOUT_SECONDS,
                check=False,
                **kwargs,
            )
        except subprocess.TimeoutExpired:
            if attempt == GIT_TIMEOUT_RETRIES:
                raise


@dataclass
class _SourceNodeCache:
    """Per-load compact indexes and aggregate source-read budget."""

    nodes_by_path: dict[Path, frozenset[tuple[str, str]] | None] = field(default_factory=dict)
    source_bytes_read: int = 0
    budget_exceeded: bool = False


def _pytest_node_id_exists(
    root: Path,
    test_id: str,
    *,
    source_cache: _SourceNodeCache | dict[Path, frozenset[tuple[str, str]] | None] | None = None,
) -> bool:
    """Resolve the statically named pytest function/class node in its source."""
    parts = test_id.split("::")
    if len(parts) not in (2, 3) or any(not part for part in parts):
        return False
    path, *selectors = parts
    if "\\" in path:
        return False
    source_path = PurePosixPath(path)
    if (source_path.is_absolute() or source_path.as_posix() != path or
            len(source_path.parts) < 2 or source_path.parts[0] != "tests" or
            any(part in ("", ".", "..") for part in source_path.parts)):
        return False
    # Parametrized IDs depend on pytest collection and may be generated by
    # runtime code. This registry accepts only source-resolvable node names.
    if any("[" in selector or "]" in selector for selector in selectors):
        return False
    try:
        repository_root = root.resolve(strict=True)
        tests_root = (repository_root / "tests").resolve(strict=True)
        target = repository_root.joinpath(*source_path.parts)
        cursor = repository_root
        for component in source_path.parts:
            cursor = cursor / component
            if cursor.is_symlink():
                return False
        resolved = target.resolve(strict=True)
        if tests_root not in resolved.parents:
            return False
    except OSError:
        return False

    if isinstance(source_cache, _SourceNodeCache):
        cache = source_cache
    else:
        # Keep direct helper calls using the earlier plain-dict cache compatible.
        cache = _SourceNodeCache(
            nodes_by_path=source_cache if source_cache is not None else {}
        )
    if resolved in cache.nodes_by_path:
        node_index = cache.nodes_by_path[resolved]
        if node_index is None:
            return False
    else:
        remaining = MAX_REGISTRY_SOURCE_BYTES - cache.source_bytes_read
        if remaining <= 0:
            cache.budget_exceeded = True
            return False
        read_limit = min(MAX_TEST_SOURCE_BYTES, remaining)
        try:
            with resolved.open("rb") as handle:
                raw_source = handle.read(read_limit + 1)
            if len(raw_source) > MAX_TEST_SOURCE_BYTES:
                cache.nodes_by_path[resolved] = None
                return False
            if len(raw_source) > remaining:
                cache.budget_exceeded = True
                return False
            cache.source_bytes_read += len(raw_source)
            source = raw_source.decode("utf-8")
            module = ast.parse(source, filename=path)
        except (OSError, UnicodeError, SyntaxError, RecursionError):
            cache.nodes_by_path[resolved] = None
            return False
        node_index: set[tuple[str, str]] = set()
        for node in module.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.name.startswith("test_"):
                    node_index.add(("", node.name))
                continue
            if not isinstance(node, ast.ClassDef) or not node.name.startswith("Test"):
                continue
            if any(
                isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef))
                and member.name in {"__init__", "__new__"}
                for member in node.body
            ):
                continue
            node_index.update(
                (node.name, member.name)
                for member in node.body
                if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef))
                and member.name.startswith("test_")
            )
        node_index = frozenset(node_index)
        cache.nodes_by_path[resolved] = node_index

    if len(selectors) == 1:
        return ("", selectors[0]) in node_index

    class_name, method_name = selectors
    if not class_name.startswith("Test") or not method_name.startswith("test_"):
        return False
    return (class_name, method_name) in node_index


def _git_commit_exists(root: Path, revision: str) -> bool:
    """Compatibility helper; provenance validation uses the ancestry query below."""
    try:
        result = subprocess.run(
            ["git", "cat-file", "-e", f"{revision}^{{commit}}"], cwd=root,
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL, timeout=5, check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def _git_commit_is_ancestor(root: Path, revision: str, candidate_head: str) -> bool:
    """Require registry provenance to be part of the candidate's history."""
    try:
        result = _run_git_with_timeout_retry(
            ["git", "merge-base", "--is-ancestor", revision, candidate_head], cwd=root,
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except subprocess.TimeoutExpired as exc:
        raise ContractError(
            "cannot verify QA registry ancestry: git merge-base timed out after "
            f"{GIT_TIMEOUT_RETRIES + 1} attempts of {GIT_COMMAND_TIMEOUT_SECONDS} seconds"
        ) from exc
    except OSError as exc:
        raise ContractError(f"cannot invoke git to verify QA registry ancestry: {exc}") from exc
    if result.returncode == 0:
        return True
    if result.returncode == 1:
        return False
    raise ContractError(
        "cannot verify QA registry ancestry: git merge-base exited "
        f"with status {result.returncode}"
    )


def _current_candidate_head(root: Path) -> str:
    try:
        result = _run_git_with_timeout_retry(
            ["git", "rev-parse", "--verify", "HEAD"], cwd=root,
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ContractError(f"cannot identify the QA candidate HEAD: {exc}") from exc
    head = result.stdout.strip()
    if result.returncode != 0 or len(head) != 40 or any(c not in "0123456789abcdef" for c in head):
        raise ContractError("cannot identify a full QA candidate HEAD")
    return head


def load_registry(root: Path, relative_path: str = "docs/qa/categories.json") -> tuple[dict, str]:
    """Validate committed registry syntax, unique IDs, categories, and source paths."""
    registry, raw = _read_repo_json(root, relative_path, max_bytes=MAX_REGISTRY_BYTES)
    tracked_cache: dict[str, bool] = {}
    ancestry_cache: dict[tuple[str, str], bool] = {}
    source_cache = _SourceNodeCache()

    def is_tracked(path: str) -> bool:
        if path not in tracked_cache:
            tracked_cache[path] = _git_file_is_tracked(root, path)
        return tracked_cache[path]

    def is_ancestor(revision: str, candidate: str) -> bool:
        pair = (revision, candidate)
        if pair not in ancestry_cache:
            ancestry_cache[pair] = _git_commit_is_ancestor(root, revision, candidate)
        return ancestry_cache[pair]

    if set(registry) != {"schema_version", "source_head", "categories", "regression"}:
        raise ContractError("QA registry has missing or unexpected top-level fields")
    if registry["schema_version"] != 1:
        raise ContractError("unsupported QA registry schema_version")
    source_head = registry["source_head"]
    if (not isinstance(source_head, str) or len(source_head) != 40 or
            any(char not in "0123456789abcdef" for char in source_head)):
        raise ContractError("QA registry source_head must be a full lowercase Git SHA")
    candidate_head = _current_candidate_head(root)
    if not is_ancestor(source_head, candidate_head):
        raise ContractError("QA registry source_head is missing, stale, or outside the candidate history")
    categories = registry["categories"]
    if not isinstance(categories, dict) or set(categories) != set(PRIMARY_CATEGORIES):
        raise ContractError("QA registry must account for every primary category")
    seen_ids: set[str] = set()
    for category in PRIMARY_CATEGORIES:
        entry = categories[category]
        if not isinstance(entry, dict) or not isinstance(entry.get("state"), str):
            raise ContractError(f"QA registry category {category!r} is malformed")
        state = entry["state"]
        if state == "NOT_RUN":
            if set(entry) != {"state", "owner_role", "reason", "next_step"}:
                raise ContractError(f"NOT_RUN category {category!r} has unexpected fields")
            if entry.get("test_ids") not in (None, []):
                raise ContractError(f"NOT_RUN category {category!r} cannot declare required IDs")
            if not isinstance(entry.get("reason"), str) or not entry["reason"]:
                raise ContractError(f"NOT_RUN category {category!r} needs a reason")
            if not isinstance(entry.get("next_step"), str) or not entry["next_step"]:
                raise ContractError(f"NOT_RUN category {category!r} needs a next step")
            continue
        if state != "SUPPORTED":
            raise ContractError(f"unknown QA category state {state!r}")
        expected_fields = {
            "state", "coverage_state", "coverage_reason", "owner_role",
            "source_head", "test_ids",
        }
        if category == "api":
            expected_fields.add("network_api")
        if set(entry) != expected_fields:
            raise ContractError(f"QA category {category!r} has missing or unexpected fields")
        if entry.get("coverage_state") not in ("PARTIAL", "COMPLETE"):
            raise ContractError(f"QA category {category!r} needs PARTIAL or COMPLETE coverage state")
        if not isinstance(entry.get("coverage_reason"), str) or not entry["coverage_reason"]:
            raise ContractError(f"QA category {category!r} needs a coverage explanation")
        if entry.get("owner_role") not in ("functional-test-reviewer", "e2e-runner"):
            raise ContractError(f"QA category {category!r} has an invalid test owner role")
        head = entry.get("source_head")
        if (not isinstance(head, str) or len(head) != 40 or
                any(char not in "0123456789abcdef" for char in head)):
            raise ContractError(f"QA category {category!r} needs a full source_head")
        if not is_ancestor(head, candidate_head):
            raise ContractError(
                f"QA category {category!r} source_head is missing, stale, or outside candidate history"
            )
        test_ids = entry.get("test_ids")
        if not isinstance(test_ids, list) or not test_ids:
            raise ContractError(f"supported QA category {category!r} needs test IDs")
        if any(not isinstance(item, str) for item in test_ids):
            raise ContractError(f"QA category {category!r} test IDs must be strings")
        if len(test_ids) != len(set(test_ids)):
            raise ContractError(f"QA category {category!r} has duplicate test IDs")
        if len(seen_ids) + len(test_ids) > MAX_REGISTRY_TEST_IDS:
            raise ContractError(
                f"QA registry exceeds the {MAX_REGISTRY_TEST_IDS} test-ID limit"
            )
        for test_id in test_ids:
            if not isinstance(test_id, str) or "::" not in test_id:
                raise ContractError(f"QA test ID is not a pytest node ID: {test_id!r}")
            path = test_id.split("::", 1)[0]
            if "\\" in path or not path.startswith("tests/") or not is_tracked(path):
                raise ContractError(f"QA test ID source is not a tracked tests path: {test_id!r}")
            if not _pytest_node_id_exists(root, test_id, source_cache=source_cache):
                if source_cache.budget_exceeded:
                    raise ContractError(
                        "QA test source validation exceeds the "
                        f"{MAX_REGISTRY_SOURCE_BYTES}-byte aggregate limit"
                    )
                raise ContractError(
                    "QA test ID does not resolve to a statically named pytest node: "
                    f"{test_id!r}"
                )
            if test_id in seen_ids:
                raise ContractError(f"QA test ID has multiple primary categories: {test_id!r}")
            seen_ids.add(test_id)
    network_api = categories["api"].get("network_api")
    if (not isinstance(network_api, dict) or
            set(network_api) != {"state", "reason"} or
            network_api["state"] != "UNSUPPORTED" or
            not isinstance(network_api["reason"], str) or not network_api["reason"]):
        raise ContractError("network API coverage must be explicitly UNSUPPORTED with a reason")
    regression = registry["regression"]
    if (not isinstance(regression, dict) or
            set(regression) != {"state", "coverage_state", "reason", "primary_categories"} or
            regression["state"] != "SUPPORTED_AGGREGATE" or
            regression["coverage_state"] not in ("PARTIAL", "COMPLETE") or
            not isinstance(regression["reason"], str) or not regression["reason"] or
            regression["primary_categories"] != list(REGRESSION_CATEGORIES)):
        raise ContractError("regression must be the ordered functional/integration/api/e2e aggregate")
    return registry, hashlib.sha256(raw).hexdigest()


def load_seeded_failure_catalog(root: Path, registry: dict) -> tuple[dict, str]:
    """Load the bounded fixture inventory and bind each fixture to one test ID."""
    if not _git_file_is_tracked(root, SEEDED_CATALOG_PATH):
        raise ContractError("seeded-failure catalog must be a tracked repository file")
    catalog, raw = _read_repo_json(
        root, SEEDED_CATALOG_PATH, max_bytes=MAX_SEEDED_CATALOG_BYTES
    )
    if set(catalog) != {"schema_version", "state", "fixtures", "reason", "next_step"}:
        raise ContractError("seeded-failure catalog has missing or unexpected fields")
    if (type(catalog["schema_version"]) is not int or catalog["schema_version"] != 1 or
            not isinstance(catalog["fixtures"], list) or
            len(catalog["fixtures"]) > 256):
        raise ContractError("seeded-failure catalog schema is invalid")
    seeded_category = registry["categories"]["seeded-failure"]
    state = catalog["state"]
    if state == "NOT_RUN":
        if (catalog["fixtures"] or not isinstance(catalog["reason"], str) or
                not catalog["reason"] or not isinstance(catalog["next_step"], str) or
                not catalog["next_step"] or seeded_category["state"] != "NOT_RUN"):
            raise ContractError("NOT_RUN seeded-failure catalog must be empty and match its category state")
        return catalog, hashlib.sha256(raw).hexdigest()
    if state != "SUPPORTED" or seeded_category["state"] != "SUPPORTED":
        raise ContractError("seeded-failure catalog and category support states disagree")
    if catalog["reason"] is not None or catalog["next_step"] is not None:
        raise ContractError("supported seeded-failure catalog cannot declare a NOT_RUN reason")
    fixture_ids: set[str] = set()
    fixture_test_ids: set[str] = set()
    for fixture in catalog["fixtures"]:
        expected_fields = {
            "fixture_id", "input", "input_sha256", "expected_rejection", "test_id",
        }
        if not isinstance(fixture, dict) or set(fixture) != expected_fields:
            raise ContractError("seeded-failure fixture has missing or unexpected fields")
        fixture_id = fixture["fixture_id"]
        if not isinstance(fixture_id, str) or not _FIXTURE_ID.fullmatch(fixture_id):
            raise ContractError("seeded-failure fixture_id is invalid")
        if fixture_id in fixture_ids:
            raise ContractError("seeded-failure catalog has duplicate fixture IDs")
        fixture_ids.add(fixture_id)
        input_record = fixture["input"]
        if not isinstance(input_record, dict):
            raise ContractError("seeded-failure fixture input must be a JSON object")
        try:
            input_bytes = json.dumps(
                input_record, sort_keys=True, separators=(",", ":"),
                ensure_ascii=True, allow_nan=False,
            ).encode("utf-8")
        except (TypeError, ValueError, RecursionError) as exc:
            raise ContractError("seeded-failure fixture input is not canonical JSON") from exc
        if len(input_bytes) > 16 * 1024:
            raise ContractError("seeded-failure fixture input exceeds 16 KiB")
        input_hash = fixture["input_sha256"]
        if (not isinstance(input_hash, str) or len(input_hash) != 64 or
                any(char not in "0123456789abcdef" for char in input_hash) or
                hashlib.sha256(input_bytes).hexdigest() != input_hash):
            raise ContractError("seeded-failure fixture input hash is invalid")
        expected_rejection = fixture["expected_rejection"]
        if (not isinstance(expected_rejection, str) or
                not _REJECTION_CODE.fullmatch(expected_rejection)):
            raise ContractError("seeded-failure expected rejection code is invalid")
        test_id = fixture["test_id"]
        if not isinstance(test_id, str) or "::" not in test_id:
            raise ContractError("seeded-failure fixture must link a pytest node ID")
        if test_id in fixture_test_ids:
            raise ContractError("a seeded-failure test ID cannot represent multiple fixtures")
        fixture_test_ids.add(test_id)
    required_test_ids = set(seeded_category["test_ids"])
    if not fixture_ids or fixture_test_ids != required_test_ids:
        raise ContractError("seeded-failure fixtures must map exactly to registered test IDs")
    return catalog, hashlib.sha256(raw).hexdigest()


def load_manifest(root: Path, relative_path: str) -> tuple[dict, str]:
    if not _git_file_is_tracked(root, relative_path):
        raise ContractError("v2 task manifest must be a tracked repository file")
    raw_manifest, _ = _read_repo_json(root, relative_path, max_bytes=2 * 1024 * 1024)
    manifest = validate_task_manifest(raw_manifest)
    if manifest.get("contract_version") != 2:
        raise ContractError("QA execution requires a v2 VST task manifest")
    return manifest, manifest_sha256(manifest)


def validate_projection(registry: dict, manifest: dict) -> None:
    """Require exact category/test-ID/selector projection into the run manifest."""
    categories: dict[str, dict[str, Any]] = registry["categories"]
    slots = {
        item["slot"]: item["receipt_type"]
        for item in manifest["required_receipts"]
        if item["receipt_type"] == "TestRun"
    }
    expected_slots = {
        category for category, entry in categories.items()
        if entry["state"] == "SUPPORTED"
    }
    if set(slots) != expected_slots:
        raise ContractError("v2 TestRun slots must exactly match supported QA primary categories")
    for category in expected_slots:
        expected = categories[category]["test_ids"]
        actual = sorted(
            item["test_id"] for item in manifest["required_tests"]
            if item["slot"] == category
        )
        if actual != sorted(expected):
            raise ContractError(f"v2 required test IDs differ from registry for {category!r}")
        commands = [
            item["argv"] for item in manifest["mandatory_commands"]
            if item["slot"] == category
        ]
        if len(commands) != 1:
            raise ContractError(f"category {category!r} needs exactly one pinned pytest command")
        expected_argv = [
            sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-p",
            "tools.qa.pytest_pass_plugin", *sorted(expected),
        ]
        if commands[0] != expected_argv:
            raise ContractError(
                f"category {category!r} command must exactly select its committed pytest node IDs"
            )
