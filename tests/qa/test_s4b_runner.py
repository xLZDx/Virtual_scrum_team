def test_report_encoding_is_canonical_single_line_with_trailing_newline():
    report = _sample_report()
    encoded = report_mod.encode_report(report)
    assert encoded.endswith(b"\n") and encoded.count(b"\n") == 1
    decoded = json.loads(encoded)
    assert decoded["normalized_sha256"] == report["normalized_sha256"]
    assert list(decoded) == sorted(decoded)  # sorted keys
    assert b", " not in encoded and b": " not in encoded  # compact separators
    assert report_mod.encode_report(dict(reversed(list(_sample_report().items())))) == encoded
