def test_concurrent_runner_on_the_same_repo_is_refused_while_the_lock_is_held(make_repo, deps):
    repo = make_repo("hang")
    scratch1, scratch2 = repo.parent / "scratch1", repo.parent / "scratch2"
    args1 = [
        PY, "-m", "tools.qa.run", "--category", "functional", "--repo-root", str(repo),
        "--dependency-target", str(deps.target), "--dependency-wheelhouse", str(deps.wheelhouse),
        "--scratch-root", str(scratch1), "--run-id", "first", "--timeout-seconds", "25",
        "--report-path", f"{EVIDENCE}/functional.report.jsonl", "--stdout-path", f"{EVIDENCE}/functional.stdout.txt",
        "--stderr-path", f"{EVIDENCE}/functional.stderr.txt",
    ]
    env = _clean_env(PYTHONPATH=str(REPO_ROOT))
    first = subprocess.Popen(args1, cwd=repo.parent, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    try:
        deadline = time.time() + 60
        while not (scratch1 / "first" / "selection.json").exists():
            assert time.time() < deadline and first.poll() is None, "first runner did not reach the pytest child"
            time.sleep(0.2)
        second = run_qa(repo, deps, "functional", run_id="second", scratch=scratch2)
        assert second.rc == 2 and "QA_RESULT BLOCKED" in second.out and "holds the evidence lock" in second.out
        assert not (scratch2 / "second").exists()
        assert second.records == [], "the refused runner must not write into the evidence the first runner owns"
    finally:
        if first.poll() is None:
            first.kill()
        first.communicate(timeout=60)
    # after the first runner is gone the lock is free again: a 1 s timeout fails the hang scenario instead of a refusal
    again = run_qa(repo, deps, "functional", run_id="third", scratch=repo.parent / "scratch3", timeout=1)
    assert again.rc == 1 and again.last["result"] == "FAIL" and "holds the evidence lock" not in again.out


