    original = run_mod._JobObject.attach
    wrappers = []

    def attach(process):
        job = original(process)
        wrapper = _ScriptedJob(job, results)
        wrappers.append(wrapper)
        return wrapper

    monkeypatch.setattr(run_mod._JobObject, "attach", staticmethod(attach))
    code, out, err, info = run_mod._run_bounded(
        [PY, "-c", "print('hello')"], cwd=tmp_path, timeout=30, cap=1000, env=run_mod.build_environment())
    assert info["job_limits"]["applied"] is True and wrappers[0].calls == 2  # exactly one retry
    assert info["cleanup_failed"] is cleanup_failed and info["capture_incomplete"] is cleanup_failed
    assert code == (run_mod.EXIT_CAPTURE_INCOMPLETE if cleanup_failed else 0)


