def _pid_alive(pid: int) -> bool:
    kernel = ctypes.windll.kernel32
    kernel.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
    kernel.OpenProcess.restype = wintypes.HANDLE
    kernel.GetExitCodeProcess.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    handle = kernel.OpenProcess(0x1000, False, pid)
    if not handle:
        return False
    try:
        code = wintypes.DWORD()
        return bool(kernel.GetExitCodeProcess(handle, ctypes.byref(code))) and code.value == 259
    finally:
        kernel.CloseHandle(handle)


def _wait_dead(pid: int, seconds: float = 15.0) -> bool:
    deadline = time.time() + seconds
    while time.time() < deadline:
        if not _pid_alive(pid):
            return True
        time.sleep(0.1)
    return not _pid_alive(pid)


def test_timeout_kills_the_whole_process_tree_and_yields_fail(make_repo, deps):
    repo = make_repo("hang")
    run = run_qa(repo, deps, "functional", run_id="hang", timeout=10)
    pid_file = run.scratch / "hang" / "grandchild.pid"
    pid = None
    try:
        assert pid_file.is_file(), "the test never spawned its grandchild; timeout may be too short\n" + run.out + run.proc.stderr
        pid = int(pid_file.read_text())
        assert _wait_dead(pid), f"grandchild {pid} survived the timeout kill"
    finally:
        if pid is not None and _pid_alive(pid):
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], capture_output=True)
    assert run.rc == 1, run.out + run.proc.stderr
    rec = run.last
    assert rec["result"] == "FAIL" and rec["capture"]["timed_out"] is True
    assert rec["exit_code"] == EXIT_TIMEOUT
    assert any("exceeded the 10s wall-clock bound; process tree killed" in r for r in rec["reasons"]), rec["reasons"]
    assert rec["passed_test_ids"] == []
    assert 9.0 <= rec["duration_seconds"] < 60  # bounded by the timeout, not by the 600 s sleeps
    assert rec["capture"]["capture_incomplete"] is False


