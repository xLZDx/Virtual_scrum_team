def assert_blocked(run: Run, needle: str, *, status: str = "BLOCKED") -> dict:
    assert run.rc == 2, run.out + run.proc.stderr
    assert f"QA_RESULT {status}" in run.out
    assert len(run.records) == 1
    record = run.last
    assert record["result"] == status
    assert any(needle in reason for reason in record["reasons"]), record["reasons"]
    assert set(record) == REPORT_FIELDS
    assert record["exit_code"] is None and record["executed_node_ids"] == [] and record["passed_test_ids"] == []
    assert not (run.scratch / run.run_id).exists(), "pytest must not have been prepared/started"
    assert run.artifact("stdout.txt").stat().st_size > 0 and run.artifact("stderr.txt").stat().st_size > 0
    return record


