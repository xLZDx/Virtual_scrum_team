class Run:
    def __init__(self, proc, repo: Path, category: str, scratch: Path, run_id: str) -> None:
        self.proc, self.repo, self.category, self.scratch, self.run_id = proc, repo, category, scratch, run_id
        self.out = proc.stdout
        self.rc = proc.returncode

    def artifact(self, kind: str) -> Path:
        return self.repo / EVIDENCE / f"{self.category}.{kind}"

    @property
    def records(self) -> list[dict]:
        path = self.artifact("report.jsonl")
        if not path.exists():
            return []
        return [json.loads(line) for line in path.read_bytes().decode("utf-8").splitlines() if line]

    @property
    def last(self) -> dict:
        return self.records[-1]


def run_qa(
    repo: Path, deps, category: str, *, run_id: str = "run1", scratch: Path | None = None,
    timeout: int = 90, cap: int | None = None, python: str = PY, target: Path | None = None,
    wheelhouse: Path | None = None, extra: list[str] | None = None, overrides: dict | None = None,
    proc_timeout: int = 240,
) -> Run:
    scratch = scratch if scratch is not None else repo.parent / "scratch"
    paths = {
        "report_path": f"{EVIDENCE}/{category}.report.jsonl",
        "stdout_path": f"{EVIDENCE}/{category}.stdout.txt",
        "stderr_path": f"{EVIDENCE}/{category}.stderr.txt",
    }
    paths.update(overrides or {})
    args = [
        str(python), "-m", "tools.qa.run", "--category", category, "--repo-root", str(repo),
        "--dependency-target", str(target or deps.target),
        "--dependency-wheelhouse", str(wheelhouse or deps.wheelhouse),
        "--scratch-root", str(scratch), "--run-id", run_id, "--timeout-seconds", str(timeout),
        "--report-path", paths["report_path"], "--stdout-path", paths["stdout_path"],
        "--stderr-path", paths["stderr_path"],
    ]
    if cap is not None:
        args += ["--output-cap-bytes", str(cap)]
    args += extra or []
    neutral = repo.parent / "neutral-cwd"
    neutral.mkdir(exist_ok=True)
    proc = subprocess.run(
        args, cwd=neutral, env=_clean_env(PYTHONPATH=str(REPO_ROOT)), capture_output=True, text=True,
        timeout=proc_timeout,
    )
    return Run(proc, repo, category, scratch, run_id)


