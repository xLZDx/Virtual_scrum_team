def build_template(root: Path, tests: dict[str, str], lock: str) -> Path:
    root.mkdir(parents=True)
    git(root, "init", "-q", "-b", "main")
    git(root, "config", "core.autocrlf", "false")
    (root / "tools" / "qa").mkdir(parents=True)
    for name in COPIED_QA_FILES:
        shutil.copyfile(QA_SRC / name, root / "tools" / "qa" / name)
    (root / "tools" / "qa" / "requirements.lock").write_bytes(lock.encode())
    (root / "tools" / "vst").mkdir()
    (root / "tools" / "vst" / "__init__.py").write_text("# vst\n", encoding="utf-8")
    (root / "docs").mkdir()
    (root / "docs" / "S4_QA_AUTOMATION_PLAN_2026-10-24.md").write_text("plan\n", encoding="utf-8")
    (root / ".gitignore").write_text("__pycache__/\n.pytest_cache/\n*.pyc\n", encoding="utf-8")
    for rel, source in tests.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source.lstrip("\n"), encoding="utf-8", newline="\n")
    commit_all(root, "base")
    built = subprocess.run(
        [PY, "-m", "tools.qa.build_registry", "--repo-root", str(root), "--write"],
        cwd=root, env=_clean_env(PYTHONPATH=str(root)), capture_output=True, text=True, timeout=120,
    )
    assert built.returncode == 0, built.stdout + built.stderr
    commit_all(root, "registry")
    return root


class Templates:
    def __init__(self, base: Path, lock: str) -> None:
        self.base, self.lock, self.cache = base, lock, {}

    def get(self, name: str) -> Path:
        if name not in self.cache:
            self.cache[name] = build_template(self.base / name, SCENARIOS[name], self.lock)
        return self.cache[name]


