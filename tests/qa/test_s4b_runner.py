def _clean_env(**extra: str) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if not k.upper().startswith("GIT_")}
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONUTF8"] = "1"
    env.pop("PYTHONPATH", None)
    env.update(extra)
    return env


def git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-c", "core.autocrlf=false", "-c", "user.name=qa", "-c", "user.email=qa@example.invalid",
         "-c", "commit.gpgsign=false", *args],
        cwd=repo, env=_clean_env(), capture_output=True, text=True, check=True, timeout=60,
    )
    return result.stdout.strip()


def commit_all(repo: Path, message: str) -> None:
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", message)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ------------------------------------------------------------------ wheel builders


def _record_hash(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip("=")


def _write_wheel(path: Path, members: dict[str, bytes], dist_info: str, *, record_tamper: bool = False) -> None:
    rows = [[n, _record_hash(d), str(len(d))] for n, d in sorted(members.items())]
    rows.append([f"{dist_info}/RECORD", "", ""])
    if record_tamper:
        rows[0][1] = "sha256=AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"
    buffer = io.StringIO()
    csv.writer(buffer, lineterminator="\n").writerows(rows)
    all_members = dict(members)
    all_members[f"{dist_info}/RECORD"] = buffer.getvalue().encode()
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in all_members.items():
            archive.writestr(name, data)


def make_wheel(
    directory: Path, name: str, version: str, files: dict[str, bytes] | None = None, *,
    tag: str = "py3-none-any", purelib: bool = True, record_tamper: bool = False,
    meta_name: str | None = None, meta_version: str | None = None,
    extra: dict[str, bytes] | None = None, filename: str | None = None,
) -> tuple[Path, str]:
    directory.mkdir(parents=True, exist_ok=True)
    stem = name.replace("-", "_")
    dist_info = f"{stem}-{version}.dist-info"
    members = dict(files if files is not None else {f"{stem}/__init__.py": f"NAME = {name!r}\n".encode()})
    members[f"{dist_info}/METADATA"] = (
        f"Metadata-Version: 2.1\nName: {meta_name or name}\nVersion: {meta_version or version}\n".encode()
    )
    members[f"{dist_info}/WHEEL"] = (
        f"Wheel-Version: 1.0\nGenerator: qa-test\nRoot-Is-Purelib: {'true' if purelib else 'false'}\n"
        f"Tag: {tag}\n".encode()
    )
    members.update(extra or {})
    path = directory / (filename or f"{stem}-{version}-{tag}.whl")
    _write_wheel(path, members, dist_info, record_tamper=record_tamper)
    return path, sha(path.read_bytes())


def lock_text(rows: list[tuple[str, str, str]], *, header: str = "# Wheel-only, exact hashes for tests.\n") -> str:
    """rows = (requirement text before ' \\', hash)."""
    out = header
    for requirement, digest, _ in rows:
        out += f"{requirement} \\\n    --hash=sha256:{digest}\n"
    return out


def make_real_dist_wheel(directory: Path, dist_name: str) -> tuple[str, str, str]:
    """Wheel rebuilt offline from an installed distribution (pure python files only)."""
    dist = importlib.metadata.distribution(dist_name)
    members: dict[str, bytes] = {}
    for entry in dist.files or []:
        rel = entry.as_posix()
        base = rel.rsplit("/", 1)[-1]
        if (
            rel.startswith("..") or "__pycache__" in rel or rel.endswith(".pyc")
            or rel.endswith(".dist-info/RECORD") or base in {"INSTALLER", "REQUESTED", "direct_url.json", "WHEEL"}
        ):
            continue
        members[rel] = Path(dist.locate_file(entry)).read_bytes()
    dist_info = next(m.split("/", 1)[0] for m in members if m.endswith(".dist-info/METADATA"))
    members[f"{dist_info}/WHEEL"] = b"Wheel-Version: 1.0\nGenerator: qa-test\nRoot-Is-Purelib: true\nTag: py3-none-any\n"
    version = dist.version
    path = directory / f"{dist_name}-{version}-py3-none-any.whl"
    _write_wheel(path, members, dist_info)
    return dist_name, version, sha(path.read_bytes())


