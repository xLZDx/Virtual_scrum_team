"""S4-D lane tests: the regression (aggregate) and e2e lanes of the S4-B runner.

Safety model is inherited from test_s4b_runner: every end-to-end case builds a fresh tiny
throw-away git repository (copy of tools/qa + synthetic tests + a registry generated by the
real builder) under tmp and runs `tools.qa.run` against it. The real repository's lanes are
never executed. Only 4 end-to-end scenarios are used; everything else is unit-level
(`_resolve_cases`, `denominator`, `count_passed`) against a generated registry or synthetic
pytest events.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import test_s4b_runner as s4b  # noqa: E402
from test_s4b_runner import deps, run_qa  # noqa: E402,F401  (deps is a session fixture)
from tools.qa import run as run_mod  # noqa: E402
from tools.qa.registry import RUNTIME_PROFILES, count_passed, denominator, validate_registry  # noqa: E402

LOCKED_PROFILES = list(RUNTIME_PROFILES)

F, I, A, E = (
    "tests/qa/test_s4_functional_a.py",
    "tests/qa/test_s4_integration_b.py",
    "tests/qa/test_s4_api_c.py",
    "tests/qa/test_s4_e2e_d.py",
)
OK = "def test_ok():\n    assert True\n"

# every member of the regression aggregate passes
REG_OK = {
    F: OK + "\n\ndef test_two():\n    assert 1 + 1 == 2\n",
    I: OK,
    A: OK,
    E: OK,
}

# one fault per kind, spread over the four aggregate members
REG_BAD = {
    F: OK + '\n\nimport pytest\n\n\n@pytest.mark.skip(reason="seeded skip")\ndef test_skipped():\n    assert True\n',
    I: OK + '\n\nimport pytest\n\n\n@pytest.mark.xfail(reason="seeded xfail")\ndef test_xfails():\n    assert False\n',
    A: (OK + '\n\ndef test_fails():\n    assert False, "seeded failure"\n'
        + "\n\ndef test_ghost():\n    assert True\n\n\ntest_ghost.__test__ = False\n"),
    E: OK + '\n\nfor _i in range(1):\n    globals()["test_dyn_%d" % _i] = (lambda: None)\n',
}

# e2e module with a sandbox-dependent selector the policy declares NOT_RUN
SBX_SEL = "tests/qa/test_s4_e2e_sbx.py::test_needs_sandbox"
SBX_REASON = "NOT_RUN: needs a run-bound sandbox that this synthetic repo does not have."
SBX = {
    F: OK,
    "tests/qa/test_s4_e2e_sbx.py": (
        "def test_local_ok():\n    assert True\n\n\n"
        "def test_needs_sandbox():\n    assert False, 'must never execute: declared NOT_RUN'\n"
    ),
}


@pytest.fixture(scope="session")
def lane_templates(tmp_path_factory, deps):
    base = tmp_path_factory.mktemp("s4d")
    patched_qa = base / "qa_src"
    shutil.copytree(s4b.QA_SRC, patched_qa, ignore=shutil.ignore_patterns("__pycache__"))
    # declare the sandbox selector NOT_RUN in the throw-away builder's policy (before its __main__ guard)
    builder = patched_qa / "build_registry.py"
    text = builder.read_text(encoding="utf-8")
    anchor = "def _runtime_profiles_for_selector("
    assert text.count(anchor) == 1
    builder.write_text(
        text.replace(anchor, f"POLICY_NOT_RUN[{SBX_SEL!r}] = {SBX_REASON!r}\n\n\n{anchor}"),
        encoding="utf-8", newline="\n",
    )
    built = {}
    for name, tests, qa_src in (
        ("reg_ok", REG_OK, s4b.QA_SRC),
        ("reg_bad", REG_BAD, s4b.QA_SRC),
        ("sbx", SBX, patched_qa),
    ):
        with pytest.MonkeyPatch.context() as mp:
            mp.setattr(s4b, "QA_SRC", qa_src)
            built[name] = s4b.build_template(base / name, tests, deps.lock_text)
    return built


@pytest.fixture
def lane_repo(tmp_path, lane_templates):
    def make(name: str) -> Path:
        repo = tmp_path / "repo"
        shutil.copytree(lane_templates[name], repo)
        return repo.resolve()
    return make


@pytest.fixture
def lane_registry(tmp_path_factory, lane_templates):
    def load(name: str):
        copy = tmp_path_factory.mktemp("reg") / "r"
        shutil.copytree(lane_templates[name], copy)
        return validate_registry(copy)
    return load


# ------------------------------------------------------------------ end-to-end (4 scenarios)


def test_regression_all_members_pass_is_a_typed_pass_over_the_whole_aggregate(lane_repo, deps):
    run = run_qa(lane_repo("reg_ok"), deps, "regression", run_id="regok")
    assert run.rc == 0, run.out + run.proc.stderr
    rec = run.last
    assert rec["result"] == "PASS" and "QA_RESULT PASS" in run.out and rec["reasons"] == []
    expected = sorted(f"{p}::{n}" for p, n in [
        (F, "test_ok"), (F, "test_two"), (I, "test_ok"), (A, "test_ok"), (E, "test_ok")])
    # the expected IDs come from the registry aggregate (all four members), not from the run
    assert rec["category"] == "regression" and rec["expected_test_ids"] == expected
    assert rec["passed_test_ids"] == expected
    for field in ("failed_test_ids", "skipped_test_ids", "xfail_test_ids", "unexpected_node_ids",
                  "uncollected_test_ids", "unassigned_test_ids"):
        assert rec[field] == [], field
    assert rec["not_run_test_reasons"] == {}
    assert {c["outcome"] for c in rec["case_outcomes"]} == {"passed"} and len(rec["case_outcomes"]) == 5


def test_regression_skip_xfail_fail_uncollected_and_extra_case_each_make_it_non_approving(lane_repo, deps):
    run = run_qa(lane_repo("reg_bad"), deps, "regression", run_id="regbad")
    assert run.rc == 1, run.out + run.proc.stderr
    rec = run.last
    assert rec["result"] == "FAIL" and "QA_RESULT FAIL" in run.out
    # only the healthy selectors from every member lane are counted as passed
    assert rec["passed_test_ids"] == sorted(f"{p}::test_ok" for p in (F, I, A, E))
    # AC-11: each defect sits in exactly the right list ...
    assert rec["skipped_test_ids"] == [f"{F}::test_skipped"]
    assert rec["xfail_test_ids"] == [f"{I}::test_xfails"]
    assert rec["failed_test_ids"] == [f"{A}::test_fails"]
    assert rec["uncollected_test_ids"] == [f"{A}::test_ghost"]
    assert rec["unexpected_node_ids"] == [f"{E}::test_dyn_0"]
    # ... and never in the passed list, nor printed as PASS
    bad = [f"{F}::test_skipped", f"{I}::test_xfails", f"{A}::test_fails", f"{A}::test_ghost"]
    for selector in bad:
        assert selector not in rec["passed_test_ids"] and f"PASS {selector}" not in run.out
    # ... with a distinct typed reason for every kind
    for needle in ("skipped cases (not passed)", "expected-failure cases", "failed or unexpectedly passed xfail",
                   "collected no cases (not passed)", "collected unmapped node IDs", "not every expected selector passed"):
        assert any(needle in r for r in rec["reasons"]), (needle, rec["reasons"])


def test_e2e_sandbox_selector_declared_not_run_stays_in_denominator_and_never_passes(lane_repo, deps):
    run = run_qa(lane_repo("sbx"), deps, "e2e", run_id="sbx")
    assert run.rc == 1, run.out + run.proc.stderr
    rec = run.last
    assert rec["result"] == "INCONCLUSIVE" and "QA_RESULT INCONCLUSIVE" in run.out  # AC-10: never PASS
    assert rec["not_run_test_reasons"] == {SBX_SEL: SBX_REASON}
    assert rec["passed_test_ids"] == ["tests/qa/test_s4_e2e_sbx.py::test_local_ok"]
    assert SBX_SEL not in rec["passed_test_ids"] and SBX_SEL not in rec["expected_test_ids"]
    assert SBX_SEL in rec["inventory_test_ids"]  # still in the denominator
    assert SBX_SEL not in rec["executed_node_ids"] and rec["failed_test_ids"] == []  # body never ran
    assert "NOT_RUN by policy" in rec["reasons"][-1]


def test_regression_aggregate_also_goes_inconclusive_when_its_e2e_member_has_a_not_run_selector(lane_repo, deps):
    run = run_qa(lane_repo("sbx"), deps, "regression", run_id="regsbx")
    assert run.rc == 1, run.out + run.proc.stderr
    rec = run.last
    assert rec["result"] == "INCONCLUSIVE"
    assert rec["not_run_test_reasons"] == {SBX_SEL: SBX_REASON}
    assert SBX_SEL in rec["inventory_test_ids"] and SBX_SEL not in rec["passed_test_ids"]
    assert set(rec["passed_test_ids"]) == {f"{F}::test_ok", "tests/qa/test_s4_e2e_sbx.py::test_local_ok"}


# ------------------------------------------------------------------ registry denominator (unit level)


def test_denominator_regression_is_exact_union_of_four_members_and_complete_only_when_all_runnable(lane_registry):
    ok = denominator(lane_registry("reg_ok"))
    assert ok["regression"] == {"expected": 5, "runnable": 5, "not_run": 0, "complete": True}
    assert ok["functional"]["expected"] + ok["integration"]["expected"] + ok["api"]["expected"] + ok["e2e"]["expected"] == 5
    sbx = denominator(lane_registry("sbx"))
    assert sbx["e2e"] == {"expected": 2, "runnable": 1, "not_run": 1, "complete": False}
    assert sbx["regression"] == {"expected": 3, "runnable": 2, "not_run": 1, "complete": False}


def test_count_passed_never_counts_the_not_run_selector_even_if_an_outcome_claims_passed(lane_registry):
    registry = lane_registry("sbx")
    # the only runtime profile any runnable selector needs here is windows; report everything passed
    outcomes = {
        profile: {
            "tests/qa/test_s4_e2e_sbx.py::test_local_ok": "passed",
            "tests/qa/test_s4_functional_a.py::test_ok": "passed",
            SBX_SEL: "passed",
        }
        for profile in LOCKED_PROFILES
    }
    counted = count_passed(registry, outcomes)
    assert counted["e2e"] == {"expected": 2, "passed": 1, "not_passed": 1, "complete": False}
    assert counted["regression"] == {"expected": 3, "passed": 2, "not_passed": 1, "complete": False}
    full = count_passed(lane_registry("reg_ok"), {
        profile: {s: "passed" for s in lane_registry("reg_ok").selectors_by_id} for profile in LOCKED_PROFILES})
    assert full["regression"]["complete"] is True and full["regression"]["passed"] == 5


# ------------------------------------------------------------------ _resolve_cases (unit level)

SELECTORS = {f"m.py::{n}": {"selector": f"m.py::{n}"} for n in ("a", "b", "c", "d", "e", "f", "g")}
EXPECTED = sorted(SELECTORS)


def _events(*rows, **extra):
    return {"collected": [{"node_id": n, "selector": s, "outcome": o} for n, s, o in rows], **extra}


def _resolve(events, expected=EXPECTED):
    return run_mod._resolve_cases(events, list(expected), SELECTORS)


def test_resolve_cases_classifies_every_outcome_into_exactly_one_list():
    res = _resolve(_events(
        ("m.py::a", "m.py::a", "passed"),
        ("m.py::b[1]", "m.py::b", "passed"), ("m.py::b[2]", "m.py::b", "skipped"),  # partial param skip
        ("m.py::c", "m.py::c", "xfailed"),
        ("m.py::d", "m.py::d", "xpassed"),
        ("m.py::e", "m.py::e", "failed"),
        ("m.py::f", "m.py::f", "not_run"),  # collected but never executed
        # g: registered, no case at all
        ("m.py::x", "m.py::zzz", "passed"),  # case mapped to no registered selector
    ))
    assert res["passed_test_ids"] == ["m.py::a"]
    assert res["skipped_test_ids"] == ["m.py::b"]
    assert res["xfail_test_ids"] == ["m.py::c"]
    assert res["failed_test_ids"] == ["m.py::d", "m.py::e", "m.py::f"]
    assert res["uncollected_test_ids"] == ["m.py::g"]
    assert res["unexpected_node_ids"] == ["m.py::x"]
    assert "m.py::f" not in res["executed_node_ids"] and "m.py::x" not in res["executed_node_ids"]
    listed = res["passed_test_ids"] + res["skipped_test_ids"] + res["xfail_test_ids"] + res["failed_test_ids"] \
        + res["uncollected_test_ids"]
    assert sorted(listed) == EXPECTED  # nothing lost, nothing double counted


def test_resolve_cases_selector_outside_the_expected_lane_is_unexpected_not_passed():
    # m.py::b is a known registry selector but not part of this lane's expected set
    res = _resolve(_events(("m.py::a", "m.py::a", "passed"), ("m.py::b", "m.py::b", "passed")), expected=["m.py::a"])
    assert res["passed_test_ids"] == ["m.py::a"] and res["unexpected_node_ids"] == ["m.py::b"]


def test_resolve_cases_failed_case_dominates_a_sibling_pass_and_skip():
    res = _resolve(_events(("m.py::a[1]", "m.py::a", "passed"), ("m.py::a[2]", "m.py::a", "failed"),
                           ("m.py::a[3]", "m.py::a", "skipped")), expected=["m.py::a"])
    assert res["failed_test_ids"] == ["m.py::a"] and res["skipped_test_ids"] == [] and res["passed_test_ids"] == []


@pytest.mark.parametrize("events", [
    {},
    {"collected": "nope"},
    _events(("m.py::a", "m.py::a", "passed"), ("m.py::a", "m.py::a", "passed")),  # duplicate node id
    _events(("m.py::a", "m.py::a", "bogus")),  # unknown outcome
])
def test_resolve_cases_rejects_malformed_event_files(events):
    with pytest.raises(run_mod.QARunError):
        _resolve(events)


def test_resolve_cases_digests_unsafe_node_ids_and_keeps_duplicates_and_collection_errors():
    res = _resolve(_events(("m.py::a[x y]", "m.py::a", "passed"), duplicates=["m.py::a"],
                           collection_errors=["bad id with spaces"]), expected=["m.py::a"])
    assert res["passed_test_ids"] == ["m.py::a"]
    assert res["collected_node_ids"][0].startswith("<unsafe-node:")
    assert res["duplicates"] == ["m.py::a"] and res["collection_errors"] == ["<unsafe-id>"]
